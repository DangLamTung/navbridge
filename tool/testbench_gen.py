#!/usr/bin/env python3
"""Generate the data file for the trip test bench (`docs/testbench.html`).

Emits `docs/testbench_trip.js` — a plain `<script src=...>` payload so the page
also works over `file://` (a fetch/XHR of a sibling JSON is blocked there).

Contains the most recent trips (fixes + announcements + places) from
`docs/trips/device`, ready for the bench's REPLAY (drive the recorded fixes) and
its LOG CHECK (announcements vs the per-fix limits, camera + rain behaviour).

Usage:
    python3 tool/testbench_gen.py            # newest 4 trips
    python3 tool/testbench_gen.py --trips 8
"""

from __future__ import annotations

import argparse
import glob
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "docs/trips/device")
OUT = os.path.join(REPO, "docs/testbench_trip.js")


def slim(path: str) -> dict:
    with open(path, encoding="utf-8") as f:
        raw = json.load(f)
    fixes = []
    for e in raw.get("locations") or []:
        lat, lng = e.get("latitudeE7"), e.get("longitudeE7")
        if lat is None or lng is None:
            continue
        fixes.append(
            {
                "t": e.get("timestampMs"),
                "lat": lat / 1e7,
                "lng": lng / 1e7,
                "v": e.get("velocity") or 0,  # m/s
                "acc": e.get("accuracy"),
                "src": e.get("source"),
                "street": e.get("street"),
                "hw": e.get("highway"),
                "road": e.get("speedLimit"),
                "eff": e.get("limitEffective"),
                "lsrc": e.get("limitSource"),
            }
        )
    return {
        "name": os.path.splitext(os.path.basename(path))[0],
        "fixes": fixes,
        "announcements": raw.get("announcements") or [],
        "places": raw.get("places") or [],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--trips", type=int, default=4, help="how many recent trips")
    args = ap.parse_args()

    files = sorted(glob.glob(os.path.join(SRC, "*.json")))[-args.trips:]
    trips = [slim(p) for p in files]
    payload = {"generated": __import__("time").strftime("%Y-%m-%d %H:%M:%S"),
               "trips": trips}
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tool/testbench_gen.py — do not edit by hand.\n")
        f.write("window.BENCH_DATA = ")
        json.dump(payload, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    total = sum(len(t["fixes"]) for t in trips)
    print(f"wrote {OUT}: {len(trips)} trips, {total} fixes")
    for t in trips:
        print(f"   {t['name']}  fixes={len(t['fixes'])} ann={len(t['announcements'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
